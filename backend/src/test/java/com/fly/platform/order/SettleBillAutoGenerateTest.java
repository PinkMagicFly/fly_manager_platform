package com.fly.platform.order;

import com.fly.platform.order.entity.CargoOrder;
import com.fly.platform.order.entity.SettleBill;
import com.fly.platform.order.enums.BillStateEnum;
import com.fly.platform.order.enums.OrderStateEnum;
import com.fly.platform.order.mapper.CargoOrderMapper;
import com.fly.platform.order.mapper.SettleBillMapper;
import com.fly.platform.order.service.CargoOrderService;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * 送达签收自动出账生成对账单单元测试
 *
 * @author SoarCloud Team
 */
@SpringBootTest
@ActiveProfiles("test")
@Transactional
public class SettleBillAutoGenerateTest {

    @Autowired
    private CargoOrderMapper cargoOrderMapper;

    @Autowired
    private SettleBillMapper settleBillMapper;

    @Autowired
    private CargoOrderService cargoOrderService;

    @Test
    @DisplayName("送达签收瞬间自动生成财务对账单测试: 金额一致性与初始待对账状态")
    void testSettleBillAutoGeneratedUponDelivery() {
        // 构造处于 50-飞行中 状态的在途运单
        BigDecimal expectedAmount = new BigDecimal("128.50");
        CargoOrder order = new CargoOrder();
        order.setOrderSn("ORDDL" + System.currentTimeMillis());
        order.setCustomerId(1L);
        order.setMerchantId(1L);
        order.setSenderAddr("前海物流仓");
        order.setReceiverAddr("香港科技大学深港协同中心");
        order.setSenderGeo("POINT(113.890 22.520)");
        order.setReceiverGeo("POINT(113.910 22.530)");
        order.setGoodsType(4);
        order.setGoodsWeight(new BigDecimal("4.20"));
        order.setFeeTotal(expectedAmount);
        order.setOrderState(OrderStateEnum.FLYING.getCode()); // 50-飞行中
        order.setPayState(1);
        order.initAudit();
        cargoOrderMapper.insertOrder(order);

        Long orderId = order.getOrderId();

        // 执行送达签收
        cargoOrderService.deliverOrder(orderId, 1001L);

        // 验证订单状态跃迁为 60-已送达
        CargoOrder deliveredOrder = cargoOrderMapper.selectOrderById(orderId);
        assertThat(deliveredOrder.getOrderState()).isEqualTo(OrderStateEnum.DELIVERED.getCode());

        // 验证数据库瞬间自动生成 settle_bill
        SettleBill bill = settleBillMapper.selectBillByOrderId(orderId);
        assertThat(bill).isNotNull();
        assertThat(bill.getBillSn()).startsWith("BILL");
        assertThat(bill.getOrderId()).isEqualTo(orderId);
        assertThat(bill.getMerchantId()).isEqualTo(1L);
        assertThat(bill.getAmount()).isEqualByComparingTo(expectedAmount);
        assertThat(bill.getBillState()).isEqualTo(BillStateEnum.PENDING_RECONCILE.getCode()); // 1-待对账
        assertThat(bill.getInvoiceFlag()).isEqualTo(0); // 0-未开票
        assertThat(bill.getSettleAt()).isNotNull();
    }
}
