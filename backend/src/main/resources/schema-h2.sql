-- H2 数据库兼容模式建表脚本
DROP TABLE IF EXISTS uam_account;
CREATE TABLE uam_account (
  account_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  login_name VARCHAR(32) NOT NULL UNIQUE,
  mobile CHAR(11) UNIQUE,
  email VARCHAR(64),
  pwd_digest VARCHAR(100) NOT NULL,
  account_kind TINYINT NOT NULL,
  status TINYINT NOT NULL DEFAULT 1,
  last_login_at TIMESTAMP,
  last_login_ip VARCHAR(45),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

DROP TABLE IF EXISTS uam_role;
CREATE TABLE uam_role (
  role_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  role_code VARCHAR(32) NOT NULL UNIQUE,
  role_name VARCHAR(64) NOT NULL,
  description VARCHAR(255),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

DROP TABLE IF EXISTS uam_account_role;
CREATE TABLE uam_account_role (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  account_id BIGINT NOT NULL,
  role_id BIGINT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

DROP TABLE IF EXISTS uam_role_grant;
CREATE TABLE uam_role_grant (
  grant_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  role_id BIGINT NOT NULL,
  perm_code VARCHAR(64) NOT NULL,
  perm_name VARCHAR(64),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

DROP TABLE IF EXISTS merchant_archive;
CREATE TABLE merchant_archive (
  merchant_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  account_id BIGINT NOT NULL,
  corp_name VARCHAR(128) NOT NULL,
  license_no VARCHAR(32) NOT NULL UNIQUE,
  contact_name VARCHAR(32) NOT NULL,
  contact_phone CHAR(11) NOT NULL,
  airworthiness_cert VARCHAR(64),
  audit_state TINYINT NOT NULL DEFAULT 0,
  audit_note VARCHAR(255),
  audit_at TIMESTAMP,
  auditor_id BIGINT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

DROP TABLE IF EXISTS customer_archive;
CREATE TABLE customer_archive (
  customer_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  account_id BIGINT NOT NULL,
  real_name VARCHAR(32) NOT NULL,
  id_card VARCHAR(18) NOT NULL,
  credit_limit DECIMAL(10,2) NOT NULL DEFAULT 5000.00,
  auth_state TINYINT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

DROP TABLE IF EXISTS cert_file;
CREATE TABLE cert_file (
  cert_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  owner_type TINYINT NOT NULL,
  owner_id BIGINT NOT NULL,
  cert_type VARCHAR(32) NOT NULL,
  file_path VARCHAR(255) NOT NULL,
  file_hash CHAR(64),
  expire_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

DROP TABLE IF EXISTS audit_log;
CREATE TABLE audit_log (
  log_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  account_id BIGINT NOT NULL,
  login_name VARCHAR(32) NOT NULL,
  module_name VARCHAR(64) NOT NULL,
  action_name VARCHAR(64) NOT NULL,
  request_uri VARCHAR(255) NOT NULL,
  client_ip VARCHAR(45) NOT NULL,
  client_kind VARCHAR(10) NOT NULL DEFAULT 'pc',
  cost_time BIGINT NOT NULL,
  req_params CLOB,
  resp_status INT NOT NULL DEFAULT 200,
  error_msg CLOB,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

DROP TABLE IF EXISTS sys_param;
CREATE TABLE sys_param (
  param_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  param_group VARCHAR(32) NOT NULL,
  param_key VARCHAR(64) NOT NULL UNIQUE,
  param_value VARCHAR(255) NOT NULL,
  param_desc VARCHAR(128),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

DROP TABLE IF EXISTS base_site;
CREATE TABLE base_site (
  site_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  site_code VARCHAR(32) NOT NULL UNIQUE,
  site_name VARCHAR(64) NOT NULL,
  site_geo VARCHAR(64) NOT NULL,
  capacity INT NOT NULL DEFAULT 4,
  occupied INT NOT NULL DEFAULT 0,
  site_state TINYINT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

DROP TABLE IF EXISTS uav_info;
CREATE TABLE uav_info (
  uav_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  uav_sn VARCHAR(32) NOT NULL UNIQUE,
  model VARCHAR(64) NOT NULL,
  merchant_id BIGINT NOT NULL,
  max_load DECIMAL(6,2) NOT NULL,
  max_range_km DECIMAL(6,1) NOT NULL,
  battery_pct TINYINT NOT NULL DEFAULT 100,
  health_score TINYINT NOT NULL DEFAULT 100,
  fly_hours INT NOT NULL DEFAULT 0,
  next_maintain_at TIMESTAMP,
  state TINYINT NOT NULL DEFAULT 0,
  home_site_id BIGINT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

DROP TABLE IF EXISTS uav_maintain;
CREATE TABLE uav_maintain (
  maintain_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  uav_id BIGINT NOT NULL,
  maintain_type TINYINT NOT NULL,
  fault_desc VARCHAR(255),
  repair_content VARCHAR(255),
  operator_id BIGINT,
  maintain_state TINYINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

DROP TABLE IF EXISTS site_booking;
CREATE TABLE site_booking (
  booking_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  site_id BIGINT NOT NULL,
  uav_id BIGINT NOT NULL,
  apply_id BIGINT,
  start_time TIMESTAMP NOT NULL,
  end_time TIMESTAMP NOT NULL,
  booking_state TINYINT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

DROP TABLE IF EXISTS crew_staff;
CREATE TABLE crew_staff (
  crew_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  account_id BIGINT NOT NULL,
  crew_type TINYINT NOT NULL,
  real_name VARCHAR(32) NOT NULL,
  license_no VARCHAR(32) NOT NULL UNIQUE,
  license_expire DATE NOT NULL,
  fly_hours INT NOT NULL DEFAULT 0,
  status TINYINT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

DROP TABLE IF EXISTS crew_shift;
CREATE TABLE crew_shift (
  shift_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  crew_id BIGINT NOT NULL,
  shift_date DATE NOT NULL,
  start_time TIME NOT NULL,
  end_time TIME NOT NULL,
  shift_state TINYINT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

